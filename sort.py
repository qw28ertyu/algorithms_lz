import random

spisok1 = random.sample(range(1,1000001), 100) # создаётся рандомный список из 100 элементов
print(spisok1) # вывод списка 

spisok2=spisok1.copy() 

# сортировка пузырьком 
stop = True # ставим флаг для остановки цикла
a = 0 # создаем счетчик сравнений  


while stop: # запускаем цикл пока не сработает стоп-флаг
    stop = False  # предполагаем, что сортировка завершена
    for i in range(len(spisok1) - 1): 
        if spisok1[i] < spisok1[i + 1]: # если текущий элемент меньше следующего 
            spisok1[i], spisok1[i + 1] = spisok1[i + 1], spisok1[i] # меняем элементы  местами  
            stop = True # стоп-флаг устанавливаем в True, чтобы продолжить цикл

            print(spisok1) # выводим промежуточный результат 
            a += 1  # увеличиваем счетчик сравнений


# сортировка выбором
b = 0 #создаем счетчик сравнений 

for i in range(len(spisok2)):
    l = i # исходно считаем наименьшим первый элемент  
    for j in range(i + 1, len(spisok2)): # этот цикл перебирает несортированные элементы 
        if spisok2[j] > spisok2[l]: # если текущий элемент больше следующего  
            l = j # находим наименьший элемент
    spisok2[i], spisok2[l] = spisok2[l], spisok2[i] # Самый маленький элемент меняем местами с первым в списке    
    print(spisok2) # выводим промежуточный результат
    b += 1  # увеличиваем количество сравнений

# Вывод отсортированных  списков
print(spisok1)
print(spisok2)

#Вывод количества сравнений
print('Количество сравнений методом пузырька',a)
print('Количество сравнений методом выбора',b)
